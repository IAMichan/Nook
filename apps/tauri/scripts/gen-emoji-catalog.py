#!/usr/bin/env python3
"""Writes src/lib/emoji-catalog-data.ts from the Mac's emoji lists, so both apps offer the same emoji with the same names.

Sources: apps/macos/Services/Messages/EmojiCatalog.swift (Unicode's groups, order and English names) and the shortcode
table in apps/macos/Services/Autocomplete/CompletionEmoji.swift (Nook's own names, Dutch ones too). Run it from the
repository root after either changes: python3 apps/tauri/scripts/gen-emoji-catalog.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CATALOG = ROOT / "apps/macos/Services/Messages/EmojiCatalog.swift"
COMPLETION = ROOT / "apps/macos/Services/Autocomplete/CompletionEmoji.swift"
OUT = ROOT / "apps/tauri/src/lib/emoji-catalog-data.ts"

# The Mac's SF Symbol per group, as NookIcon maps it to Lucide.
ICONS = {"face.smiling": "smile", "hand.wave": "hand", "pawprint": "paw-print", "fork.knife": "utensils", "car": "car",
         "soccerball": "volleyball", "lightbulb": "lightbulb", "heart": "heart", "flag": "flag"}


def table(text: str) -> list[str]:
    return [line.strip() for line in text.strip("\n").split("\n") if line.strip()]


catalog = CATALOG.read_text()
groups = []
for key, symbol, body in re.findall(r'\("(\w+)", "([\w.]+)", """\n(.*?)"""\)', catalog, re.S):
    groups.append({"key": key, "icon": ICONS[symbol], "table": "\n".join(table(body))})
assert len(groups) == 9, f"expected 9 groups, found {len(groups)}"

completion = COMPLETION.read_text()
shortcodes = re.search(r'private static let table = """\n(.*?)"""', completion, re.S).group(1)

lines = [
    "// Generated by scripts/gen-emoji-catalog.py from the Mac's EmojiCatalog.swift and CompletionEmoji.swift; do not edit.",
    "// Every emoji in Unicode's groups and order with its English name (Emoji 15.1, fully qualified, no skin tones), and",
    "// Nook's own names for the common ones (`emoji[*] name other names…`, * for an emoji that takes a skin tone).",
    "export const EMOJI_GROUPS: { key: string; icon: string; table: string }[] = " + json.dumps(groups, ensure_ascii=False, indent=2) + ";",
    "",
    "export const EMOJI_SHORTCODES = " + json.dumps("\n".join(table(shortcodes)), ensure_ascii=False) + ";",
    "",
]
OUT.write_text("\n".join(lines))
print(f"{OUT.relative_to(ROOT)}: {sum(g['table'].count(chr(10)) + 1 for g in groups)} emoji in {len(groups)} groups")
