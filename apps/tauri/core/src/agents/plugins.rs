//! Kleine plugins voor agents die code laden in plaats van hook-commando's te starten (OpenCode, Amp, Hermes)
//! (`AgentPlugins` op de Mac). Elke plugin start Nooks hook-commando met `--agent <naam>` en één regel JSON; de agent
//! wacht er nooit op. Draait Nook niet, dan gebeurt er niets. Een plugin beslist nooit iets voor de agent.
//! Elk bestand bevat de markering `nook-hook`: Nook wijzigt of verwijdert alleen bestanden die hij zelf maakte.

/// Staat in elk bestand dat Nook maakt (ook het pad naar het hook-commando bevat het).
pub const MARKER: &str = "nook-hook";

/// Een JSON-tekst is ook een geldige tekstconstante in JavaScript, TypeScript en Python.
pub fn literal(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// `~/.config/opencode/plugins/nook.js`
pub fn open_code(hook: &str) -> String {
    r#"// Nook plugin for OpenCode: generated by Nook (nook-hook). Managed by Nook.
// Relays OpenCode activity to Nook's bar. Non-blocking; no-op if Nook is not running.
import { spawn } from 'node:child_process';

const HOOK = __HOOK__;
const EVENTS = {
  'session.created': 'SessionStart',
  'session.idle': 'Stop',
  'session.error': 'StopFailure',
  'session.deleted': 'SessionEnd',
};
const TOOLS = { bash: 'Bash', edit: 'Edit', write: 'Write', read: 'Read', grep: 'Grep', glob: 'Glob', webfetch: 'WebFetch', task: 'Task' };

function forward(hook_event_name, fields) {
  try {
    const p = spawn(HOOK, ['--agent', 'opencode'], { stdio: ['pipe', 'ignore', 'ignore'], detached: true, windowsHide: true });
    p.on('error', () => {});
    p.stdin.on('error', () => {});
    p.stdin.end(JSON.stringify({ hook_event_name, ...fields }) + '\n');
    p.unref();
  } catch {}
}

function toolName(tool) {
  if (typeof tool !== 'string') return '';
  return TOOLS[tool] || tool;
}

// OpenCode writes filePath and oldString; Nook reads Claude Code canonical names.
function toolInput(args) {
  if (!args || typeof args !== 'object') return {};
  const input = { ...args };
  if (args.filePath !== undefined && input.file_path === undefined) input.file_path = args.filePath;
  if (args.oldString !== undefined && input.old_string === undefined) input.old_string = args.oldString;
  if (args.newString !== undefined && input.new_string === undefined) input.new_string = args.newString;
  return input;
}

export const NookPlugin = async ({ directory } = {}) => ({
  event: async ({ event }) => {
    const name = EVENTS[event?.type];
    if (!name) return;
    const props = event.properties || {};
    forward(name, { session_id: props.sessionID || props.info?.id || '', cwd: directory || '' });
  },
  'chat.message': async (input, output) => {
    const parts = Array.isArray(output?.parts) ? output.parts : [];
    const prompt = parts.filter((p) => p && p.type === 'text' && typeof p.text === 'string').map((p) => p.text).join('\n');
    forward('UserPromptSubmit', { session_id: input?.sessionID || '', cwd: directory || '', prompt });
  },
  'tool.execute.before': async (input, output) => {
    forward('PreToolUse', {
      session_id: input?.sessionID || '',
      cwd: directory || '',
      tool_name: toolName(input?.tool),
      tool_input: toolInput(output?.args),
    });
  },
  'tool.execute.after': async (input) => {
    forward('PostToolUse', {
      session_id: input?.sessionID || '',
      cwd: directory || '',
      tool_name: toolName(input?.tool),
    });
  },
});
"#
    .replace("__HOOK__", &literal(hook))
}

/// `~/.config/amp/plugins/nook.ts`
pub fn amp(hook: &str) -> String {
    r#"// Nook plugin for Amp: generated by Nook (nook-hook). Managed by Nook.
// For observation only: non-blocking; the plugin never intervenes in agent decisions.
import { spawn } from 'node:child_process';

const HOOK = __HOOK__;

function forward(hook_event_name: string, fields: Record<string, unknown>): void {
  try {
    const p = spawn(HOOK, ['--agent', 'amp'], { stdio: ['pipe', 'ignore', 'ignore'], detached: true, windowsHide: true });
    p.on('error', () => {});
    p.stdin?.on('error', () => {});
    p.stdin?.end(JSON.stringify({ hook_event_name, ...fields }) + '\n');
    p.unref();
  } catch {}
}

export default function (amp: any): void {
  const base = (e: any) => ({ session_id: e?.thread?.id ?? '', cwd: process.cwd() });
  amp.on('session.start', (e: any) => { forward('SessionStart', base(e)); });
  amp.on('agent.start', (e: any) => {
    forward('UserPromptSubmit', { ...base(e), prompt: typeof e?.message === 'string' ? e.message : '' });
  });
  // One step per tool once finished: listening to tool.call would require providing
  // a verdict for Amp, which Nook never does. nook_show_step shows the step and closes it immediately.
  amp.on('tool.result', (e: any) => {
    forward('PostToolUse', {
      ...base(e),
      tool_name: typeof e?.tool === 'string' ? e.tool : '',
      tool_input: e?.input && typeof e.input === 'object' ? e.input : {},
      nook_show_step: true,
    });
  });
  amp.on('agent.end', (e: any) => { forward('Stop', { ...base(e), status: e?.status ?? '' }); });
}
"#
    .replace("__HOOK__", &literal(hook))
}

/// `~/.hermes/plugins/nook/__init__.py`
pub fn hermes_init(hook: &str) -> String {
    r#"# Nook plugin for Hermes Agent: generated by Nook (nook-hook). Managed by Nook.
# Sessions and tools stream to Nook asynchronously: Hermes handles all approvals directly.
import json, os, subprocess, sys, threading

HOOK = __HOOK__
_current_session_id = ''


def _fire(fields):
    # Invoke the hook command asynchronously; a background thread cleans up the process.
    def _run():
        try:
            fields.setdefault('cwd', os.getcwd())
            extra = {'creationflags': 0x08000000} if sys.platform == 'win32' else {'start_new_session': True}
            p = subprocess.Popen([HOOK, '--agent', 'hermes'], stdin=subprocess.PIPE,
                                 stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, **extra)
            p.stdin.write(json.dumps(fields).encode() + b'\n')
            p.stdin.close()
            p.wait(timeout=5)
        except Exception:
            pass
    threading.Thread(target=_run, daemon=True).start()


def _session(kwargs, key='session_id'):
    return kwargs.get(key, '') or _current_session_id


def register(ctx):
    def on_session_start(**kwargs):
        global _current_session_id
        _current_session_id = kwargs.get('session_id', '')
        _fire({'hook_event_name': 'SessionStart', 'session_id': _current_session_id,
               'platform': kwargs.get('platform', 'cli') or 'cli'})

    def on_session_end(**kwargs):
        # Stop is handled in post_llm_call, including the final response.
        if kwargs.get('interrupted'):
            _fire({'hook_event_name': 'StopFailure', 'session_id': _session(kwargs),
                   'error': 'interrupted'})

    def post_llm_call(**kwargs):
        _fire({'hook_event_name': 'Stop', 'session_id': _session(kwargs),
               'last_assistant_message': kwargs.get('assistant_response', '') or ''})

    def pre_tool_call(**kwargs):
        args = kwargs.get('args')
        _fire({'hook_event_name': 'PreToolUse', 'session_id': _session(kwargs),
               'tool_name': kwargs.get('tool_name', ''),
               'tool_input': args if isinstance(args, dict) else {}})

    def post_tool_call(**kwargs):
        _fire({'hook_event_name': 'PostToolUse', 'session_id': _session(kwargs),
               'tool_name': kwargs.get('tool_name', '')})

    def pre_approval_request(**kwargs):
        # Observational only: Hermes prompts and handles approvals; Nook shows it is waiting for input.
        command = kwargs.get('command', '') or kwargs.get('description', '')
        _fire({'hook_event_name': 'Notification', 'session_id': _session(kwargs, 'session_key'),
               'message': ('Hermes is waiting for your approval: ' + command) if command
                          else 'Hermes is waiting for your approval'})

    ctx.register_hook('on_session_start', on_session_start)
    ctx.register_hook('on_session_end', on_session_end)
    ctx.register_hook('post_llm_call', post_llm_call)
    ctx.register_hook('pre_tool_call', pre_tool_call)
    ctx.register_hook('post_tool_call', post_tool_call)
    ctx.register_hook('pre_approval_request', pre_approval_request)
"#
    .replace("__HOOK__", &literal(hook))
}

