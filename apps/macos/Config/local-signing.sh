#!/bin/sh
# Writes Config/Signing.local.xcconfig so local builds keep one signing identity and macOS stops asking for Keychain
# access and privacy permissions (microphone, screen recording, accessibility, automation…) after every build.
# Runs automatically before `xcodegen` (preGenCommand in project.yml).
#
# 1. An Apple Development certificate in your keychain (or DEVELOPMENT_TEAM in the environment) is used when there is one.
# 2. Otherwise a self-signed "Nook Local Signing" identity is created once in your login keychain, and the scheme's
#    post-build action (Config/resign-local.sh) re-signs every build with it. Its signature stays the same across builds,
#    so permissions you granted stay granted. Set NOOK_NO_LOCAL_IDENTITY=1 to skip this and keep ad-hoc signing.
#
# A Signing.local.xcconfig you wrote by hand (without the marker below) is left alone. Never fails the generation.
cd "$(dirname "$0")" || exit 0
LOCAL=Signing.local.xcconfig
MARKER="// Generated by local-signing.sh"
LOCAL_NAME="Nook Local Signing"

if [ -f "$LOCAL" ] && ! grep -q "$MARKER" "$LOCAL"; then exit 0; fi
command -v security >/dev/null 2>&1 || exit 0

TEAM_ID="${DEVELOPMENT_TEAM:-$(security find-certificate -c "Apple Development" -p 2>/dev/null | openssl x509 -noout -subject 2>/dev/null | sed -n 's/.*OU *= *\([A-Z0-9]\{10\}\).*/\1/p' | head -n 1)}"
if [ -n "$TEAM_ID" ]; then
  {
    echo "$MARKER"
    echo "CODE_SIGN_IDENTITY = Apple Development"
    echo "DEVELOPMENT_TEAM = $TEAM_ID"
  } > "$LOCAL"
  echo "local-signing: signing with Apple Development (team $TEAM_ID)."
  exit 0
fi

# SHA-1 of the local identity, also when macOS does not trust it (self-signed): codesign accepts it all the same.
local_identity() {
  security find-identity -p codesigning 2>/dev/null | sed -n "s/.*\([0-9A-F]\{40\}\) \"$LOCAL_NAME\".*/\1/p" | head -n 1
}

create_local_identity() {
  # macOS's own LibreSSL writes a PKCS#12 file that `security import` reads; OpenSSL 3 needs -legacy for that.
  SSL=/usr/bin/openssl
  [ -x "$SSL" ] || SSL=openssl
  LEGACY=""
  "$SSL" version 2>/dev/null | grep -q '^OpenSSL 3' && LEGACY="-legacy"
  KEYCHAIN="$(security login-keychain 2>/dev/null | sed 's/^ *"\(.*\)"$/\1/')"
  [ -n "$KEYCHAIN" ] || return 1
  TMP="$(mktemp -d)" || return 1
  cat > "$TMP/req.cnf" <<EOF
[req]
distinguished_name = dn
prompt = no
[dn]
CN = $LOCAL_NAME
[ext]
basicConstraints = critical,CA:false
keyUsage = critical,digitalSignature
extendedKeyUsage = critical,codeSigning
EOF
  PASS="nook-$$"
  "$SSL" req -x509 -newkey rsa:2048 -nodes -days 7300 -config "$TMP/req.cnf" -extensions ext \
      -keyout "$TMP/key.pem" -out "$TMP/cert.pem" >/dev/null 2>&1 \
    && "$SSL" pkcs12 -export $LEGACY -inkey "$TMP/key.pem" -in "$TMP/cert.pem" -name "$LOCAL_NAME" \
      -out "$TMP/identity.p12" -passout "pass:$PASS" >/dev/null 2>&1 \
    && security import "$TMP/identity.p12" -k "$KEYCHAIN" -P "$PASS" -T /usr/bin/codesign >/dev/null 2>&1
  STATUS=$?
  rm -rf "$TMP"
  return $STATUS
}

IDENTITY=""
if [ -z "$NOOK_NO_LOCAL_IDENTITY" ]; then
  IDENTITY="$(local_identity)"
  if [ -z "$IDENTITY" ] && create_local_identity; then
    IDENTITY="$(local_identity)"
    [ -n "$IDENTITY" ] && echo "local-signing: created \"$LOCAL_NAME\" in your login keychain (once)."
  fi
fi

if [ -z "$IDENTITY" ]; then
  rm -f "$LOCAL"
  echo "local-signing: no signing identity; Nook is signed ad hoc and macOS asks for permissions after every build."
  exit 0
fi

{
  echo "$MARKER"
  echo "// Xcode signs ad hoc; the scheme's post-build action re-signs with this stable identity (Config/resign-local.sh)."
  echo "NOOK_LOCAL_SIGNING_IDENTITY = $IDENTITY"
} > "$LOCAL"
echo "local-signing: signing with \"$LOCAL_NAME\" ($IDENTITY)."
exit 0
