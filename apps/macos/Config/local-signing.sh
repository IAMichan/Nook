#!/bin/sh
# Writes Config/Signing.local.xcconfig with the team of the Apple Development certificate in your keychain, so local
# builds keep one signing identity and macOS stops asking for Keychain access and permissions after every build.
# Runs automatically before `xcodegen` (preGenCommand in project.yml). Set DEVELOPMENT_TEAM to pick a team yourself.
# A Signing.local.xcconfig you wrote by hand (without the marker below) is left alone. Never fails the generation.
cd "$(dirname "$0")" || exit 0
LOCAL=Signing.local.xcconfig
MARKER="// Generated by local-signing.sh"

if [ -f "$LOCAL" ] && ! grep -q "$MARKER" "$LOCAL"; then exit 0; fi
command -v security >/dev/null 2>&1 || exit 0

TEAM_ID="${DEVELOPMENT_TEAM:-$(security find-certificate -c "Apple Development" -p 2>/dev/null | openssl x509 -noout -subject 2>/dev/null | sed -n 's/.*OU *= *\([A-Z0-9]\{10\}\).*/\1/p' | head -n 1)}"
if [ -z "$TEAM_ID" ]; then
  echo "local-signing: no Apple Development certificate found; Nook is signed ad hoc and macOS asks for Keychain access after every build."
  exit 0
fi

{
  echo "$MARKER"
  echo "CODE_SIGN_IDENTITY = Apple Development"
  echo "DEVELOPMENT_TEAM = $TEAM_ID"
} > "$LOCAL"
echo "local-signing: signing with Apple Development (team $TEAM_ID)."
exit 0
