// The real marks of the AI brands Nook talks to (Claude, OpenAI, Gemini, Mistral, Ollama, Grok, Groq, OpenRouter, DeepSeek,
// Qwen, Kimi, LM Studio, Meta, Gemma, OpenCode, Cursor), as vector paths so they stay sharp at any size and need no image assets.
// The marks belong to their owners and are used here only to say which model or agent is meant.

enum BrandLogo: String, CaseIterable {
    case claude, openai, gemini, mistral, ollama, grok, groq, openrouter, deepseek, qwen, kimi, lmstudio, meta, gemma, opencode, cursor

    /// The brand a model or agent name points at ("claude-haiku-5-5", "Qwen 3 (4B)", "gpt-4o", "Codex"), if we have its mark.
    static func forName(_ raw: String) -> BrandLogo? {
        let name = raw.lowercased()
        let table: [(String, BrandLogo)] = [
            ("claude", .claude), ("anthropic", .claude), ("codex", .openai), ("openai", .openai), ("gpt", .openai),
            ("gemma", .gemma), ("gemini", .gemini), ("mistral", .mistral), ("mixtral", .mistral), ("ollama", .ollama),
            ("grok", .grok), ("groq", .groq), ("openrouter", .openrouter), ("deepseek", .deepseek), ("qwen", .qwen),
            ("kimi", .kimi), ("moonshot", .kimi), ("lm studio", .lmstudio), ("lmstudio", .lmstudio), ("llama", .meta),
            ("opencode", .opencode), ("cursor", .cursor)
        ]
        return table.first { name.contains($0.0) }?.1
    }

    /// The mark for a provider.
    static func forProvider(_ provider: AIProvider) -> BrandLogo {
        switch provider {
        case .claude, .claudeCode: return .claude
        case .openai: return .openai
        case .gemini: return .gemini
        case .grok: return .grok
        case .mistral: return .mistral
        case .groq: return .groq
        case .openrouter: return .openrouter
        case .deepseek: return .deepseek
        case .qwen: return .qwen
        case .moonshot: return .kimi
        case .ollama: return .ollama
        case .lmstudio: return .lmstudio
        }
    }

    /// The brand color of the mark; light or dark (following the surface) for the brands whose mark is black or white.
    var style: AnyShapeStyle {
        switch self {
        case .claude: return AnyShapeStyle(Color(hex: 0xD97757))
        case .gemini, .gemma:
            return AnyShapeStyle(LinearGradient(colors: [Color(hex: 0x4F8BF7), Color(hex: 0x9B72F2)], startPoint: .bottomLeading, endPoint: .topTrailing))
        case .mistral: return AnyShapeStyle(Color(hex: 0xFA520F))
        case .groq: return AnyShapeStyle(Color(hex: 0xF55036))
        case .openrouter: return AnyShapeStyle(Color(hex: 0x8B8EFF))
        case .deepseek: return AnyShapeStyle(Color(hex: 0x5B7BFF))
        case .qwen: return AnyShapeStyle(Color(hex: 0x7C78F5))
        case .kimi: return AnyShapeStyle(Color(hex: 0x3A9BFF))
        case .meta: return AnyShapeStyle(Color(hex: 0x1D9BF0))
        case .openai, .ollama, .grok, .lmstudio, .opencode, .cursor: return AnyShapeStyle(Self.ink)
        }
    }

    /// Whether the mark is one plain color (black or white in the brand's own art), so it can follow the text color.
    var isMonochrome: Bool { [.openai, .ollama, .grok, .lmstudio, .opencode, .cursor].contains(self) }

    /// Light on dark surfaces (the notch, the workspace), dark on light ones (Settings in light mode).
    private static let ink = Color(nsColor: NSColor(name: nil) { appearance in
        appearance.bestMatch(from: [.darkAqua, .aqua]) == .aqua ? NSColor(white: 0.1, alpha: 1)
            : NSColor(red: 0xF4 / 255, green: 0xF3 / 255, blue: 0xF7 / 255, alpha: 1)  // NookTheme.paper
    })

    fileprivate func paths(_ point: (CGFloat, CGFloat) -> CGPoint) -> [Path] {
        switch self {
        case .claude: return BrandPaths.claude(point)
        case .openai: return BrandPaths.openai(point)
        case .gemini: return BrandPaths.gemini(point)
        case .mistral: return BrandPaths.mistral(point)
        case .ollama: return BrandPaths.ollama(point)
        case .grok: return BrandPaths.grok(point)
        case .groq: return BrandPaths.groq(point)
        case .openrouter: return BrandPaths.openrouter(point)
        case .deepseek: return BrandPaths.deepseek(point)
        case .qwen: return BrandPaths.qwen(point)
        case .kimi: return BrandPaths.kimi(point)
        case .lmstudio: return BrandPaths.lmstudio(point)
        case .meta: return BrandPaths.meta(point)
        case .gemma: return BrandPaths.gemma(point)
        case .opencode: return BrandPaths.opencode(point)
        case .cursor: return BrandPaths.cursor(point)
        }
    }
}

/// A brand's mark at a given size, in its own color.
struct BrandMark: View {
    let logo: BrandLogo
    var size: CGFloat = 14

    var body: some View {
        Canvas { context, canvas in
            let scale = min(canvas.width, canvas.height) / 24
            let origin = CGPoint(x: (canvas.width - 24 * scale) / 2, y: (canvas.height - 24 * scale) / 2)
            let point: (CGFloat, CGFloat) -> CGPoint = { CGPoint(x: origin.x + $0 * scale, y: origin.y + $1 * scale) }
            for path in logo.paths(point) {
                context.fill(path, with: .style(logo.style), style: FillStyle(eoFill: true))
            }
        }
        .frame(width: size, height: size)
    }
}

/// Logos as plain images, for the places that can't show a view: menu items and pickers.
@MainActor
enum LogoImage {
    private static var cache: [String: NSImage] = [:]

    static func brand(_ logo: BrandLogo, size: CGFloat = 14) -> Image {
        render("brand-\(logo.rawValue)-\(size)", template: logo.isMonochrome) { BrandMark(logo: logo, size: size) }
    }

    static func agent(_ agent: String, size: CGFloat = 14) -> Image {
        let name = agent.lowercased()
        let template = !name.contains("antigravity") && BrandLogo.forName(name)?.isMonochrome == true
        return render("agent-\(agent)-\(size)", template: template) { AgentLogo(agent: agent, size: size) }
    }

    static func agent(_ kind: AgentKind, size: CGFloat = 14) -> Image { agent(kind.name, size: size) }

    /// One-color marks become template images, so menus draw them in their own text color (dark in light mode).
    private static func render<Content: View>(_ key: String, template: Bool, _ content: () -> Content) -> Image {
        if let cached = cache[key] { return Image(nsImage: cached) }
        let renderer = ImageRenderer(content: content())
        renderer.scale = NSScreen.main?.backingScaleFactor ?? 2
        guard let image = renderer.nsImage else { return Image(systemName: "circle.fill") }
        image.isTemplate = template
        cache[key] = image
        return Image(nsImage: image)
    }
}

