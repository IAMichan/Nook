    #if os(macOS)
    /// The icon as an AppKit image (menus, the Dock menu, drawn layers): Lucide when the table has one.
    static func nsImage(_ symbol: String, accessibilityDescription: String? = nil) -> NSImage? {
        if let name = lucide(for: symbol), let image = NSImage(symbolName: name, bundle: .main, variableValue: 0) {
            image.accessibilityDescription = accessibilityDescription
            return image
        }
        return NSImage(systemSymbolName: symbol, accessibilityDescription: accessibilityDescription)
    }
    #endif
}

extension Image {
    /// An icon named the SF Symbol way, drawn as Nook's Lucide icon when there is one (`NookIcon`).
    init(icon symbol: String) {
        if let name = NookIcon.lucide(for: symbol) {
            self.init(name, bundle: .main)
        } else {
            self.init(systemName: symbol)
        }
    }
}
