import XCTest

/// Agent credits left out of a merge commit, human co-authors kept (`AgentCredits`, `PullRequestMergeMessage`).
final class AgentCreditsTests: XCTestCase {
    func testAgentTrailersGoAndPeopleStay() {
        let message = """
        Fix the login on mobile

        The session expired too early.

        Co-Authored-By: Claude Opus 4.5 <noreply@anthropic.com>
        Co-authored-by: Ann de Vries <ann@example.com>
        Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>
        Co-authored-by: Cursor Agent <cursoragent@cursor.com>
        co-authored-by: gemini-code-assist[bot] <176961590+gemini-code-assist[bot]@users.noreply.github.com>
        Co-authored-by: Codex <codex@openai.com>
        Co-authored-by: aider (gpt-4o) <noreply@aider.chat>
        """
        XCTAssertEqual(AgentCredits.strip(message), """
        Fix the login on mobile

        The session expired too early.

        Co-authored-by: Ann de Vries <ann@example.com>
        """)
    }

    func testGeneratedLineNeedsTheAgentRightAfterIt() {
        XCTAssertTrue(AgentCredits.isGeneratedLine("🤖 Generated with [Claude Code](https://claude.com/claude-code)"))
        XCTAssertTrue(AgentCredits.isGeneratedLine("Generated by GitHub Copilot"))
        XCTAssertFalse(AgentCredits.isGeneratedLine("Generated by running gemini against fixtures"))
    }

    func testGeneratedLinesGoWithTheBlankLinesTheyLeave() {
        let message = "Add charts\n\n- bar chart\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n"
        XCTAssertEqual(AgentCredits.strip(message), "Add charts\n\n- bar chart")
        XCTAssertEqual(AgentCredits.strip("Body\n\nGenerated by Codex\n\nMore"), "Body\n\nMore", "one blank line where the line was")
    }

    func testWhatIsNotAnAgentStays() {
        let message = "Regenerate protos\n\nGenerated with protoc 3.21\nCo-authored-by: Claude Monet <claude@monet.fr>\nCo-authored-by: Bob <bob@anthropic.com>"
        XCTAssertEqual(AgentCredits.strip(message), message, "a person named Claude, an Anthropic employee and protoc are not agents")
        XCTAssertEqual(AgentCredits.strip("Plain message\n"), "Plain message\n", "nothing to remove: unchanged, to the byte")
    }

    func testAgentsByAddress() {
        XCTAssertTrue(AgentCredits.isAgent(name: "Claude", email: "NoReply@Anthropic.com"))
        XCTAssertTrue(AgentCredits.isAgent(name: "copilot-swe-agent[bot]", email: "198982749+Copilot@users.noreply.github.com"))
        XCTAssertTrue(AgentCredits.isAgent(name: "x", email: "devin-ai-integration[bot]@users.noreply.github.com"))
        XCTAssertTrue(AgentCredits.isAgent(name: "Gemini CLI", email: "gemini-cli@no-reply.google.com"), "an agent's name with a no-reply address")
        XCTAssertFalse(AgentCredits.isAgent(name: "Ann", email: "12345+ann@users.noreply.github.com"), "a person's GitHub no-reply address")
        XCTAssertFalse(AgentCredits.isAgent(name: "Gemini Smith", email: "gemini@smith.dev"))
    }

    // MARK: The merge commit

    private let settings = PullRequestMergeMessage.Settings()

    func testRepositorySettingsAreRead() {
        let read = PullRequestMergeMessage.Settings(repository: ["squash_merge_commit_message": "PR_BODY", "squash_merge_commit_title": "PR_TITLE"])
        XCTAssertEqual(read.squashMessage, "PR_BODY")
        XCTAssertEqual(read.squashTitle, "PR_TITLE")
        XCTAssertEqual(read.mergeTitle, "MERGE_MESSAGE", "GitHub's default when the repository does not say")
    }

    func testGitHubsDefaultCommits() {
        let one = PullRequestMergeMessage.defaults(method: .squash, number: 7, title: "Login", body: "PR body", headLabel: "me/fix",
                                                   commits: ["Fix login\n\nDetails"], settings: settings)
        XCTAssertEqual(one?.title, "Fix login (#7)")
        XCTAssertEqual(one?.message, "Details")
        let many = PullRequestMergeMessage.defaults(method: .squash, number: 7, title: "Login", body: "", headLabel: "me/fix",
                                                    commits: ["A", "B\n\nwhy"], settings: settings)
        XCTAssertEqual(many?.title, "Login (#7)")
        XCTAssertEqual(many?.message, "* A\n\n* B\n\nwhy")
        let merge = PullRequestMergeMessage.defaults(method: .merge, number: 7, title: "Login", body: "", headLabel: "me/fix",
                                                     commits: [], settings: settings)
        XCTAssertEqual(merge?.title, "Merge pull request #7 from me/fix")
        XCTAssertEqual(merge?.message, "Login")
        XCTAssertNil(PullRequestMergeMessage.defaults(method: .rebase, number: 7, title: "", body: "", headLabel: "", commits: [], settings: settings))
    }

    private func commit(_ message: String, login: String? = nil, name: String = "", email: String = "") -> PullRequestMergeMessage.Commit {
        PullRequestMergeMessage.Commit(message: message, login: login, name: name, email: email)
    }

    func testOnlyACommitWithCreditsIsChanged() {
        let clean = [commit("Fix\n\nCo-authored-by: Ann <ann@example.com>", login: "me", name: "Me", email: "me@example.com")]
        XCTAssertNil(PullRequestMergeMessage.withoutCredits(method: .squash, number: 1, title: "T", body: "", headLabel: "",
                                                            commits: clean, merger: "me", settings: settings),
                     "nothing to strip: GitHub's own commit stands")
        XCTAssertNil(PullRequestMergeMessage.withoutCredits(method: .rebase, number: 1, title: "T", body: "", headLabel: "",
                                                            commits: [commit("A\n\nCo-Authored-By: Claude <noreply@anthropic.com>")],
                                                            merger: nil, settings: settings))
    }

    func testASquashKeepsThePeopleGitHubWouldCredit() {
        let commits = [
            commit("Start\n\nCo-Authored-By: Claude <noreply@anthropic.com>", login: "me", name: "Me", email: "me@example.com"),
            commit("Polish", login: "ann", name: "Ann", email: "ann@example.com"),
            commit("Bot fix", login: "Copilot", name: "Copilot", email: "175728472+Copilot@users.noreply.github.com"),
            commit("More", login: "ann", name: "Ann", email: "ann@example.com"),
        ]
        let override = PullRequestMergeMessage.withoutCredits(method: .squash, number: 3, title: "Feature", body: "", headLabel: "me/f",
                                                              commits: commits, merger: "me", settings: settings)
        XCTAssertNil(override?.title, "the title had no credits: GitHub's stands")
        XCTAssertEqual(override?.message, "* Start\n\n* Polish\n\n* Bot fix\n\n* More\n\nCo-authored-by: Ann <ann@example.com>",
                       "the merger and the agent are not credited; Ann once")
    }

    func testAMergeCommitFromThePullRequestBody() {
        let body = "Summary\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"
        var merging = settings
        merging.mergeMessage = "PR_BODY"
        let override = PullRequestMergeMessage.withoutCredits(method: .merge, number: 9, title: "T", body: body, headLabel: "me/f",
                                                              commits: [], merger: nil, settings: merging)
        XCTAssertEqual(override, .init(title: nil, message: "Summary"))
    }

    func testTheMergeRequestCarriesTheMessage() {
        let body = PullRequestDetailParser.mergeBody(method: .squash, sha: "abc", message: .init(title: nil, message: "Clean"))
        XCTAssertEqual(body["commit_message"] as? String, "Clean")
        XCTAssertNil(body["commit_title"])
        XCTAssertEqual(body["sha"] as? String, "abc")
        let rebase = PullRequestDetailParser.mergeBody(method: .rebase, sha: "", message: .init(title: "T", message: "M"))
        XCTAssertNil(rebase["commit_message"], "a rebase takes no message")
        XCTAssertNil(PullRequestDetailParser.mergeBody(method: .merge, sha: "abc")["commit_message"], "without the setting: as before")
    }
}
