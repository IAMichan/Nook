/// Every emoji Teams offers as a reaction, by the key Teams keeps it under: its own names for the oldest ones ("like",
/// "cwl" for 😂, "smile"), and the code points with the emoji's name for the newer ones ("1f64f_foldedhands", with
/// "-tone1"…"-tone5" for a skin tone). From Microsoft's reaction reference
/// (learn.microsoft.com/microsoftteams/platform/agents-in-teams/teams-reactions-reference). Teams shows a placeholder
/// for a key it does not have, so Nook sends only keys from this list, and reads them back to their emoji.
enum TeamsEmoji {
    /// The emoji of a key ("cwl" → 😂).
    static let byKey: [String: String] = {
        var keys: [String: String] = [:]
        for line in table.split(separator: "\n") {
            guard let space = line.firstIndex(of: " ") else { continue }
            keys[String(line[..<space])] = String(line[line.index(after: space)...])
        }
        return keys
    }()

    /// The key to send for an emoji: the first one the list gives it, the variation selector left out so "❤" and
    /// "❤️" are the same heart.
    static let byEmoji: [String: String] = {
        var emoji: [String: String] = [:]
        for line in table.split(separator: "\n") {
            guard let space = line.firstIndex(of: " ") else { continue }
            let key = bare(String(line[line.index(after: space)...]))
            if emoji[key] == nil { emoji[key] = String(line[..<space]) }
        }
        return emoji
    }()

    static func bare(_ emoji: String) -> String {
        String(String.UnicodeScalarView(emoji.unicodeScalars.filter { $0.value != 0xFE0F }))
    }

