import Foundation

/// Lightweight plugins for agents that load code instead of executing hook commands (OpenCode, Amp, Hermes).
/// Each plugin runs Nook's hook script with `--agent <name>` passing a single JSON line; the agent never blocks.
/// If Nook is not running, nothing happens. Where the agent lets a plugin answer its own permission prompt (OpenCode's
/// `permission.asked` with its reply route, Hermes' approval transport), the plugin hands the prompt to Nook as a
/// `PermissionRequest` (`--wait`) and gives your answer back; without an answer the agent asks you itself, as before.
/// Amp offers no such prompt to a plugin (see docs/INTEGRATIONS.md).
/// Each file contains a maker comment: Nook only updates or removes files it created itself.
enum AgentPlugins {
    /// Present in every file generated by Nook; the path to the hook script (nook-hook.sh) is also embedded.
    static let marker = "nook-hook"

    /// Path to the hook script as an escaped string literal valid across JavaScript, TypeScript, and Python.
    static var hookLiteral: String {
        literal(NookPaths.hookScriptURL.path)
    }

    /// A JSON string is also a valid string literal in JavaScript, TypeScript, and Python.
    static func literal(_ text: String) -> String {
        var out = "\""
        for scalar in text.unicodeScalars {
            switch scalar {
            case "\"": out += "\\\""
            case "\\": out += "\\\\"
            case "\n": out += "\\n"
            case "\r": out += "\\r"
            case "\t": out += "\\t"
            default:
                if scalar.value < 0x20 {
                    out += String(format: "\\u%04x", scalar.value)
                } else {
                    // Other characters remain unchanged: all three languages support UTF-8.
                    out.unicodeScalars.append(scalar)
                }
            }
        }
        return out + "\""
    }

    // MARK: OpenCode

    /// ~/.config/opencode/plugins/nook.js
    static var openCode: String {
        #"""
        // Nook plugin for OpenCode: generated by Nook (nook-hook). Managed by Nook.
        // Relays OpenCode activity to the notch, and its permission prompts so you can answer them there too.
        // Non-blocking; no-op if Nook is not running. OpenCode's own prompt stays: whichever answer comes first counts.
        import { spawn } from 'node:child_process';

        const HOOK = \#(hookLiteral);
        const EVENTS = {
          'session.created': 'SessionStart',
          'session.idle': 'Stop',
          'session.error': 'StopFailure',
          'session.deleted': 'SessionEnd',
          'session.compacted': 'PostCompact',
        };
        const TOOLS = { bash: 'Bash', edit: 'Edit', write: 'Write', read: 'Read', grep: 'Grep', glob: 'Glob', webfetch: 'WebFetch', task: 'Task' };

        function forward(hook_event_name, fields) {
          try {
            const p = spawn(HOOK, ['--agent', 'opencode'], { stdio: ['pipe', 'ignore', 'ignore'], detached: true });
            p.on('error', () => {});
            p.stdin.on('error', () => {});
            p.stdin.end(JSON.stringify({ hook_event_name, ...fields }) + '\n');
            p.unref();
          } catch {}
        }

        function toolName(tool) {
          if (typeof tool !== 'string') return '';
          return TOOLS[tool] || tool;
        }

        // Permission prompts waiting for your answer in Nook, by request id: the hook script waiting on the notch.
        const asking = new Map();

        // Asks Nook and resolves with its one-line answer ('' when there is none: Nook not running, or no answer in time).
        function ask(fields) {
          return new Promise((resolve) => {
            try {
              const p = spawn(HOOK, ['--agent', 'opencode', '--wait'], { stdio: ['pipe', 'pipe', 'ignore'] });
              let out = '';
              p.stdout.on('data', (chunk) => { out += chunk; });
              p.on('error', () => resolve(''));
              p.on('close', () => resolve(out.trim()));
              p.stdin.on('error', () => {});
              p.stdin.end(JSON.stringify({ hook_event_name: 'PermissionRequest', ...fields }) + '\n');
              if (fields.request_id) asking.set(fields.request_id, p);
            } catch { resolve(''); }
          });
        }

        // Nook's answer as OpenCode's: 'once', 'always', 'reject', or '' (no answer: OpenCode keeps asking you).
        function verdict(line) {
          try {
            const decision = JSON.parse(line)?.hookSpecificOutput?.decision || {};
            if (decision.behavior === 'deny') return 'reject';
            if (decision.behavior === 'allow') return decision.updatedPermissions ? 'always' : 'once';
          } catch {}
          return '';
        }

        // The reply route of OpenCode's server; the older per-session route for versions before it.
        async function reply(serverUrl, sessionID, id, answer) {
          if (!serverUrl) return;
          const base = String(serverUrl).replace(/\/$/, '');
          const post = (path, body) => fetch(base + path, {
            method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body),
          }).then((r) => r.ok).catch(() => false);
          if (await post(`/permission/${encodeURIComponent(id)}/reply`, { reply: answer })) return;
          await post(`/session/${encodeURIComponent(sessionID)}/permissions/${encodeURIComponent(id)}`, { response: answer });
        }

        // A permission prompt (permission.asked, or permission.updated in older versions) as a PermissionRequest.
        async function permission(props, directory, serverUrl) {
          const id = props.id || props.requestID;
          const sessionID = props.sessionID || '';
          if (!id || asking.has(id)) return;
          const kind = props.permission || props.type || props.action || '';
          const patterns = [].concat(props.patterns || props.pattern || props.resources || []).filter((x) => typeof x === 'string');
          const input = toolInput(props.metadata);
          if (input.command === undefined && (kind === 'bash' || kind === 'shell') && patterns.length) input.command = patterns.join(' && ');
          if (input.description === undefined && typeof props.title === 'string') input.description = props.title;
          if (!Object.keys(input).length && patterns.length) input.patterns = patterns;
          const canAlways = Array.isArray(props.always) ? props.always.length > 0 : true;
          const answer = verdict(await ask({
            session_id: sessionID, cwd: directory || '', request_id: id, tool_name: toolName(kind), tool_input: input,
            permission_suggestions: canAlways ? [{ type: 'opencode', always: props.always || patterns }] : [],
          }));
          asking.delete(id);
          if (answer) await reply(serverUrl, sessionID, id, answer);
        }

        // OpenCode writes filePath and oldString; Nook reads Claude Code canonical names.
        function toolInput(args) {
          if (!args || typeof args !== 'object') return {};
          const input = { ...args };
          if (args.filePath !== undefined && input.file_path === undefined) input.file_path = args.filePath;
          if (args.oldString !== undefined && input.old_string === undefined) input.old_string = args.oldString;
          if (args.newString !== undefined && input.new_string === undefined) input.new_string = args.newString;
          return input;
        }

        export const NookPlugin = async ({ directory, serverUrl } = {}) => ({
          event: async ({ event }) => {
            const props = event?.properties || {};
            if (event?.type === 'permission.asked' || event?.type === 'permission.updated') {
              // Not awaited: OpenCode's own prompt shows meanwhile, and its events keep flowing.
              permission(props, directory, serverUrl);
              return;
            }
            if (event?.type === 'permission.replied') {
              // You answered in OpenCode: the card in the notch goes (the waiting hook closes).
              const id = props.permissionID || props.requestID || props.id;
              asking.get(id)?.kill();
              asking.delete(id);
              return;
            }
            const name = EVENTS[event?.type];
            if (!name) return;
            const fields = { session_id: props.sessionID || props.info?.id || '', cwd: directory || '' };
            // A failed turn passes its error, so Nook can tell a usage limit or an expired login from other failures.
            const error = props.error?.data?.message || props.error?.message || props.error?.name;
            if (name === 'StopFailure' && typeof error === 'string' && error) fields.error = error;
            forward(name, fields);
          },
          'chat.message': async (input, output) => {
            const parts = Array.isArray(output?.parts) ? output.parts : [];
            const prompt = parts.filter((p) => p && p.type === 'text' && typeof p.text === 'string').map((p) => p.text).join('\n');
            forward('UserPromptSubmit', { session_id: input?.sessionID || '', cwd: directory || '', prompt });
          },
          'tool.execute.before': async (input, output) => {
            forward('PreToolUse', {
              session_id: input?.sessionID || '',
              cwd: directory || '',
              tool_name: toolName(input?.tool),
              tool_input: toolInput(output?.args),
            });
          },
          'tool.execute.after': async (input) => {
            forward('PostToolUse', {
              session_id: input?.sessionID || '',
              cwd: directory || '',
              tool_name: toolName(input?.tool),
            });
          },
          // Right before OpenCode summarizes the session; the summary itself is left as it is.
          'experimental.session.compacting': async (input) => {
            forward('PreCompact', { session_id: input?.sessionID || '', cwd: directory || '' });
          },
        });

        """#
    }

    // MARK: Amp

    /// ~/.config/amp/plugins/nook.ts
    static var amp: String {
        #"""
        // Nook plugin for Amp: generated by Nook (nook-hook). Managed by Nook.
        // For observation only: non-blocking; the plugin never intervenes in agent decisions.
        import { spawn } from 'node:child_process';

        const HOOK = \#(hookLiteral);

        function forward(hook_event_name: string, fields: Record<string, unknown>): void {
          try {
            const p = spawn(HOOK, ['--agent', 'amp'], { stdio: ['pipe', 'ignore', 'ignore'], detached: true });
            p.on('error', () => {});
            p.stdin?.on('error', () => {});
            p.stdin?.end(JSON.stringify({ hook_event_name, ...fields }) + '\n');
            p.unref();
          } catch {}
        }

        export default function (amp: any): void {
          const base = (e: any) => ({ session_id: e?.thread?.id ?? '', cwd: process.cwd() });
          amp.on('session.start', (e: any) => { forward('SessionStart', base(e)); });
          amp.on('agent.start', (e: any) => {
            forward('UserPromptSubmit', { ...base(e), prompt: typeof e?.message === 'string' ? e.message : '' });
          });
          // One step per tool once finished: listening to tool.call would require providing
          // a verdict for Amp, which Nook never does. nook_show_step shows the step and closes it immediately.
          amp.on('tool.result', (e: any) => {
            forward('PostToolUse', {
              ...base(e),
              tool_name: typeof e?.tool === 'string' ? e.tool : '',
              tool_input: e?.input && typeof e.input === 'object' ? e.input : {},
              nook_show_step: true,
            });
          });
          amp.on('agent.end', (e: any) => { forward('Stop', { ...base(e), status: e?.status ?? '' }); });
        }

        """#
    }

    // MARK: Hermes

    /// ~/.hermes/plugins/nook/__init__.py
    static var hermesInit: String {
        #"""
        # Nook plugin for Hermes Agent: generated by Nook (nook-hook). Managed by Nook.
        # Sessions and tools stream to the notch asynchronously. With security.approval.transport: nook in
        # ~/.hermes/config.yaml, Hermes' approvals are answered in the notch; without an answer Hermes falls back
        # (security.approval.transport_fallback: builtin shows its own prompt).
        import json, os, subprocess, threading

        HOOK = \#(hookLiteral)
        _current_session_id = ''


        def _fire(fields):
            # Invoke the hook script asynchronously; background thread cleans up the process.
            def _run():
                try:
                    fields.setdefault('cwd', os.getcwd())
                    p = subprocess.Popen([HOOK, '--agent', 'hermes'], stdin=subprocess.PIPE,
                                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                         start_new_session=True)
                    p.stdin.write(json.dumps(fields).encode() + b'\n')
                    p.stdin.close()
                    p.wait(timeout=5)
                except Exception:
                    pass
            threading.Thread(target=_run, daemon=True).start()


        def _session(kwargs, key='session_id'):
            return kwargs.get(key, '') or _current_session_id


        def _present(request):
            # Hermes' approval transport: asks Nook and waits; Hermes keeps policy and stores "session" / "always".
            choices = list(getattr(request, 'allowed_choices', ()) or ('once', 'deny'))
            later = [c for c in ('session', 'always') if c in choices]
            fields = {'hook_event_name': 'PermissionRequest', 'session_id': _current_session_id, 'cwd': os.getcwd(),
                      'tool_name': 'Bash',
                      'tool_input': {'command': getattr(request, 'command', '') or '',
                                     'description': getattr(request, 'description', '') or ''},
                      'permission_suggestions': [{'type': 'hermes', 'choice': later[0]}] if later else []}
            seconds = getattr(request, 'timeout_seconds', 0) or 300
            try:
                p = subprocess.run([HOOK, '--agent', 'hermes', '--wait'], input=json.dumps(fields).encode() + b'\n',
                                   stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=max(5, min(seconds - 5, 130)))
                answer = json.loads(p.stdout.decode() or '{}')
            except Exception:
                answer = {}
            decision = ((answer.get('hookSpecificOutput') or {}).get('decision') or {}) if isinstance(answer, dict) else {}
            behavior = decision.get('behavior')
            if behavior == 'deny' and 'deny' in choices:
                return request.respond('deny')
            if behavior == 'allow':
                if decision.get('updatedPermissions') and later:
                    return request.respond(later[0])
                if 'once' in choices:
                    return request.respond('once')
            # No answer in Nook: Hermes' transport_fallback decides (builtin: its own prompt).
            raise RuntimeError('No answer from Nook')


        def register(ctx):
            def on_session_start(**kwargs):
                global _current_session_id
                _current_session_id = kwargs.get('session_id', '')
                _fire({'hook_event_name': 'SessionStart', 'session_id': _current_session_id,
                       'platform': kwargs.get('platform', 'cli') or 'cli'})

            def on_session_end(**kwargs):
                # Stop is handled in post_llm_call, including the final response.
                if kwargs.get('interrupted'):
                    _fire({'hook_event_name': 'StopFailure', 'session_id': _session(kwargs),
                           'error': 'interrupted'})

            def post_llm_call(**kwargs):
                _fire({'hook_event_name': 'Stop', 'session_id': _session(kwargs),
                       'last_assistant_message': kwargs.get('assistant_response', '') or ''})

            def pre_tool_call(**kwargs):
                args = kwargs.get('args')
                _fire({'hook_event_name': 'PreToolUse', 'session_id': _session(kwargs),
                       'tool_name': kwargs.get('tool_name', ''),
                       'tool_input': args if isinstance(args, dict) else {}})

            def post_tool_call(**kwargs):
                _fire({'hook_event_name': 'PostToolUse', 'session_id': _session(kwargs),
                       'tool_name': kwargs.get('tool_name', '')})

            def pre_approval_request(**kwargs):
                # Observational only: Hermes prompts and handles approvals; notch indicates it is waiting for input.
                command = kwargs.get('command', '') or kwargs.get('description', '')
                _fire({'hook_event_name': 'Notification', 'session_id': _session(kwargs, 'session_key'),
                       'message': ('Hermes is waiting for your approval: ' + command) if command
                                  else 'Hermes is waiting for your approval'})

            ctx.register_hook('on_session_start', on_session_start)
            ctx.register_hook('on_session_end', on_session_end)
            ctx.register_hook('post_llm_call', post_llm_call)
            ctx.register_hook('pre_tool_call', pre_tool_call)
            ctx.register_hook('post_tool_call', post_tool_call)
            ctx.register_hook('pre_approval_request', pre_approval_request)
            # Hermes versions with approval transports; used once config.yaml selects it.
            if hasattr(ctx, 'register_approval_transport'):
                ctx.register_approval_transport('nook', _present)

        """#
    }

