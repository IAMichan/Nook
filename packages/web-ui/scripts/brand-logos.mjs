// Turns the brand marks the Mac app draws (apps/macos/UI/Components/BrandLogo.swift, paths on a 24×24 grid) into SVG
// paths for the web surfaces: src/brandLogos.ts. Run it after a mark changes there: `node scripts/brand-logos.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const swift = readFileSync(here('../../../apps/macos/UI/Components/BrandLogo.swift'), 'utf8');
const body = swift.slice(swift.indexOf('private enum BrandPaths'));

const n = (v) => String(Number(Number(v).toFixed(3)));
const point = /P\(([-\d.]+), ([-\d.]+)\)/g;
const marks = {};
for (const block of body.split(/static func /).slice(1)) {
  const name = block.match(/^(\w+)\(/)[1];
  const paths = [];
  for (const part of block.split('var p = Path()').slice(1)) {
    let d = '';
    for (const line of part.split('\n')) {
      const pts = [...line.matchAll(point)].map((m) => `${n(m[1])} ${n(m[2])}`);
      if (line.includes('p.move(')) d += `M${pts[0]}`;
      else if (line.includes('p.addLine(')) d += `L${pts[0]}`;
      // Swift writes the end point first, SVG last.
      else if (line.includes('p.addCurve(')) d += `C${pts[1]} ${pts[2]} ${pts[0]}`;
      else if (line.includes('p.addQuadCurve(')) d += `Q${pts[1]} ${pts[0]}`;
      else if (line.includes('p.closeSubpath(')) d += 'Z';
      else if (line.includes('result.append(p)')) break;
    }
    paths.push(d);
  }
  marks[name] = paths;
}

const out = `// Generated by scripts/brand-logos.mjs from apps/macos/UI/Components/BrandLogo.swift: do not edit by hand.
// The marks belong to their owners and are used here only to say which model or agent is meant.

/** Each brand's paths on a 24×24 grid, filled even-odd. */
export const brandPaths: Record<string, readonly string[]> = ${JSON.stringify(marks, null, 2)};
`;
writeFileSync(here('../src/brandLogos.ts'), out);
console.log(Object.keys(marks).join(', '));
