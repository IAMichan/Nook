import Foundation
import SwiftUI

/// Ondersteunde talen voor de app-interface.
public enum AppLanguage: String, CaseIterable, Identifiable, Sendable {
    case nl = "nl"
    case en = "en"
    case de = "de"

    public var id: String { rawValue }

    public var displayName: String {
        switch self {
        case .nl: return "Nederlands"
        case .en: return "English"
        case .de: return "Deutsch"
        }
    }
}

/// Centrale vertaalbeheerder voor Nook.
/// Ondersteunt directe vertaalsleutels en dynamisch wisselen van taal zonder herstart.
public final class I18n: ObservableObject, @unchecked Sendable {
    public static let shared = I18n()

    private let lock = NSLock()
    private var cachedLanguage: AppLanguage

    public var currentLanguage: AppLanguage {
        lock.lock()
        defer { lock.unlock() }
        return cachedLanguage
    }

    @Published public var language: AppLanguage {
        didSet {
            lock.lock()
            cachedLanguage = language
            lock.unlock()
            UserDefaults.standard.set(language.rawValue, forKey: "appLanguage")
        }
    }

    private init() {
        let initial: AppLanguage
        if let saved = UserDefaults.standard.string(forKey: "appLanguage"),
           let lang = AppLanguage(rawValue: saved) {
            initial = lang
        } else {
            let preferred = Locale.preferredLanguages.first?.prefix(2).lowercased() ?? "nl"
            if preferred == "en" { initial = .en }
            else if preferred == "de" { initial = .de }
            else { initial = .nl }
        }
        self.cachedLanguage = initial
        self.language = initial
    }

    public static func lookup(_ key: String, for lang: AppLanguage) -> String {
        if let val = translations[lang]?[key] {
            return val
        }
        if lang != .nl, let val = translations[.nl]?[key] {
            return val
        }
        if lang != .en, let val = translations[.en]?[key] {
            return val
        }
        return key
    }

    public func lookup(_ key: String, for lang: AppLanguage) -> String {
        Self.lookup(key, for: lang)
    }

    public func tr(_ key: String, _ args: CVarArg...) -> String {
        let lang = currentLanguage
        let format = Self.lookup(key, for: lang)
        if args.isEmpty {
            return format
        }
        return String(format: format, locale: Locale(identifier: lang.rawValue), arguments: args)
    }
}

/// Vertaalt een sleutel naar de actieve taal.
public func tr(_ key: String, _ args: CVarArg...) -> String {
    let lang = I18n.shared.currentLanguage
    let format = I18n.lookup(key, for: lang)
    if args.isEmpty {
        return format
    }
    return String(format: format, locale: Locale(identifier: lang.rawValue), arguments: args)
}

